CODEFORCES_API = "https://codeforces.com/api/user.info"


def fetch_codeforces_max_rating(handle):
    """
    Fetch the user's maximum Codeforces rating.

    Return 'N/A' if the API is unavailable, the response is invalid,
    or the account has no maxRating yet.
    """
    query = urlencode({"handles": handle})
    url = f"{CODEFORCES_API}?{query}"

    request = Request(
        url,
        headers={
            "Accept": "application/json",
            "User-Agent": "GitHub-Profile-Terminal/1.0",
        },
    )

    try:
        with urlopen(request, timeout=10) as response:
            payload = json.load(response)

        if payload.get("status") != "OK":
            message = payload.get("comment", "Unknown API error")
            print(f"Codeforces API error: {message}")
            return "N/A"

        users = payload.get("result", [])

        if not users:
            print("Codeforces API returned no users.")
            return "N/A"

        rating = users[0].get("maxRating")

        if not isinstance(rating, int) or isinstance(rating, bool):
            print("Codeforces account has no maximum rating yet.")
            return "N/A"

        print(f"Codeforces max rating: {rating}")
        return str(rating)

    except (
        HTTPError,
        URLError,
        TimeoutError,
        OSError,
        ValueError,
        TypeError,
        AttributeError,
        IndexError,
    ) as error:
        print(f"Could not fetch Codeforces rating: {error}")
        return "N/A"


def safe_url(value):
    parsed = urlparse(value)

    if (
        parsed.scheme != "https"
        or not parsed.netloc
        or re.search(r"[\s<>()]", value)
    ):
        raise ValueError("Links must be valid HTTPS URLs")

    return value


def html_text(value):
    return escape(str(value), quote=True)


def get_activity_snapshot(readme_path):
    """
    Preserve the GitHub activity section generated by the other workflow.
    """
    if readme_path.exists():
        old_readme = readme_path.read_text(encoding="utf-8")
    else:
        old_readme = ""

    if (
        old_readme.count(START) == 1
        and old_readme.count(END) == 1
        and old_readme.index(START) < old_readme.index(END)
    ):
        return old_readme[
            old_readme.index(START):
            old_readme.index(END) + len(END)
        ]

    return (
        START
        + "\n\n"
        + "*Activity appears after the first successful refresh.*"
        + "\n\n"
        + END
    )


def render_terminal(data):
    roles = data["roles"]

    if len(roles) != 3:
        raise ValueError("Provide exactly three roles in data.json")

    # UTC timestamp of this generation, not a continuously updating clock.
    last_updated = datetime.now(timezone.utc).strftime(
        "%Y-%m-%d %H:%M:%SZ"
    )

    values = {
        "NAME": data["name"],
        "TITLE": data["title"],
        "BIO": data["bio"],
        "CF_RATING": fetch_codeforces_max_rating(
            CODEFORCES_HANDLE
        ),
        "LAST_UPDATED": last_updated,
    }

    values.update({
        f"ROLE_{index}": role
        for index, role in enumerate(roles, start=1)
    })

    template_path = ROOT / "terminal.template.svg"
    template = template_path.read_text(encoding="utf-8")

    def replace_placeholder(match):
        key = match.group(1)

        if key not in values:
            raise ValueError(
                f"Unknown SVG template placeholder: {key}"
            )

        # Escape dynamic values so they remain valid SVG/XML text.
        return escape(str(values[key]), quote=True)

    rendered = re.sub(
        r"{{([A-Z0-9_]+)}}",
        replace_placeholder,
        template,
    )

    # Validate the generated SVG before writing it.
    ET.fromstring(rendered)

    output_path = ROOT / "terminal.svg"
    output_path.write_text(rendered, encoding="utf-8")

    print(f"Generated {output_path.name}")
    print(f"Last updated: {last_updated}")


